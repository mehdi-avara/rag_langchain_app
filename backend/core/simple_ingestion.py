def detect_type(file_bytes: bytes) -> str:
    if file_bytes.startswith(b'%PDF'):
        return 'pdf'
    if file_bytes.startswith(b'---'):
        return 'md'
    if file_bytes.startswith(b'#'):
        return 'txt'
    if file_bytes.startswith(b'![') and file_bytes.endswith(b']'):
        return 'image'
    return 'unknown'


def extract_text_from_md(file_bytes: bytes) -> Tuple[str, int, List[Dict]]:
    candidate_encodings = ['utf-8', 'utf-8-sig', 'cp1252', 'latin-1']
    for enc in candidate_encodings:
        try:
            text = file_bytes.decode(enc)
            break
        except UnicodeDecodeError:
            continue
    else:
        text = file_bytes.decode('utf-8', errors='replace')

    text = text.replace('\r\n', '\n').replace('\r', '\n')
    return text, 1, []


def run_mineru_sync(original_pdf_path: str, doc_dir: str):
    timeout_seconds = int(os.getenv("MINERU_TIMEOUT_SECONDS", "900"))
    cpuset = os.getenv("MINERU_CPUSET", "0-5")
    method = os.getenv("MINERU_METHOD", "auto")
    formula_enabled = os.getenv("MINERU_ENABLE_FORMULA", "false").lower() in ("1", "true", "yes")
    table_enabled = os.getenv("MINERU_ENABLE_TABLE", "false").lower() in ("1", "true", "yes")

    cmd = [
        "taskset", "-c", cpuset,
        settings.mineru_running_address,
        "-p", str(original_pdf_path),
        "-o", str(doc_dir),
        "-m", method,
        "-f", "true" if formula_enabled else "false",
        "-t", "true" if table_enabled else "false",
    ]

    env = os.environ.copy()

    print("MinerU START", flush=True)
    print("MinerU CMD:", " ".join(cmd), flush=True)
    print("MinerU CWD:", str(doc_dir), flush=True)
    print("MinerU TIMEOUT:", timeout_seconds, flush=True)

    try:
        result = subprocess.run(
            cmd,
            env=env,
            check=True,
            capture_output=True,
            text=True,
            cwd=doc_dir,
            timeout=timeout_seconds,
        )
        print("MinerU DONE", flush=True)
        print("MinerU STDOUT:\n", result.stdout[-4000:], flush=True)
        print("MinerU STDERR:\n", result.stderr[-4000:], flush=True)
        return result.stdout

    except subprocess.TimeoutExpired as e:
        print("MinerU TIMEOUT", flush=True)
        print("Timeout seconds:", timeout_seconds, flush=True)
        print("STDOUT:\n", (e.stdout or "")[-4000:] if isinstance(e.stdout, str) else e.stdout, flush=True)
        print("STDERR:\n", (e.stderr or "")[-4000:] if isinstance(e.stderr, str) else e.stderr, flush=True)
        raise RuntimeError(f"MinerU timed out after {timeout_seconds} seconds") from e

    except subprocess.CalledProcessError as e:
        print("MinerU FAILED", flush=True)
        print("Return code:", e.returncode, flush=True)
        print("STDOUT:\n", (e.stdout or "")[-4000:], flush=True)
        print("STDERR:\n", (e.stderr or "")[-4000:], flush=True)
        raise RuntimeError(f"MinerU failed with return code {e.returncode}") from e


def process_pdf_with_mineru(pdf_path: str, doc_id: int, base_dir: str, storage_path: str | None = None) -> str:
    doc_dir = Path(base_dir) / (storage_path or str(doc_id))
    doc_dir.mkdir(parents=True, exist_ok=True)
    run_mineru_sync(Path(base_dir) / pdf_path, doc_dir)
    middle_json_file = get_full_processed_file_path(doc_dir, "_middle.json")
    if middle_json_file:
        return middle_json_file

    raise Exception("No _middle.json file generated by MinerU")


def extract_pdf_pages_with_pypdf(pdf_path: str) -> List[Dict]:
    from pypdf import PdfReader

    reader = PdfReader(str(pdf_path))
    pages = []

    for index, page in enumerate(reader.pages):
        try:
            text = page.extract_text() or ""
        except Exception:
            text = ""

        text = text.replace("\r\n", "\n").replace("\r", "\n").strip()
        if text:
            pages.append({
                "page_num": index + 1,
                "text": text,
            })

    return pages


def make_simple_chunks_from_pages(pages: List[Dict], max_chars: int = 3500, overlap_chars: int = 400) -> List[Dict]:
    chunks = []

    for page in pages:
        text = page["text"]
        page_num = page["page_num"]

        start = 0
        text_len = len(text)

        while start < text_len:
            end = min(start + max_chars, text_len)
            chunk_body = text[start:end].strip()

            if chunk_body:
                token_count = max(1, len(chunk_body.split()))
                chunks.append({
                    "page_num": page_num,
                    "content": chunk_body,
                    "token_count": token_count,
                })

            if end >= text_len:
                break

            start = max(0, end - overlap_chars)

    return chunks


def save_text_chunks(
    doc_id: int,
    chunks: List[Dict],
    n_pages: int,
    document_version_id: int | None = None,
    storage_path: str | None = None,
) -> int:
    embedding_inputs = [f"search_document: {chunk['content']}" for chunk in chunks]
    embeddings = generate_embeddings_for_chunks(embedding_inputs) if chunks else []

    chunk_records = []
    current_pos = 0
    effective_storage_path = storage_path or str(doc_id)

    for index, chunk in enumerate(chunks):
        content = chunk["content"]
        start_pos = current_pos
        end_pos = start_pos + len(content)
        current_pos = end_pos

        embedding = embeddings[index] if index < len(embeddings) else None
        version_part = document_version_id if document_version_id is not None else "current"

        holder = Chunk(
            doc_id=doc_id,
            document_version_id=document_version_id,
            page_num=int(chunk["page_num"]),
            token_count=int(chunk["token_count"]),
            content=content,
            start_pos=start_pos,
            end_pos=end_pos,
            chunk_type="text",
            embedding=embedding,
            vdb_id=f"{doc_id}_{version_part}_{index}",
            es_id=f"{doc_id}_{version_part}_{index}",
        )
        chunk_records.append(holder)

    with db_session() as db:
        if document_version_id is not None:
            db.query(Chunk).filter(
                Chunk.doc_id == doc_id,
                Chunk.document_version_id == document_version_id,
            ).delete(synchronize_session=False)

            version = db.query(DocumentVersion).filter(
                DocumentVersion.id == document_version_id,
                DocumentVersion.document_id == doc_id,
            ).first()

            if version:
                version.n_pages = n_pages
                version.n_chunks = len(chunk_records)
                version.file_path = effective_storage_path

            doc = db.query(Document).filter(Document.id == doc_id).first()
            if doc and doc.current_version_id == document_version_id:
                doc.n_pages = n_pages
                doc.n_chunks = len(chunk_records)
                doc.file_path = effective_storage_path
        else:
            db.query(Chunk).filter(Chunk.doc_id == doc_id).delete(synchronize_session=False)
            db.query(Document).filter(Document.id == doc_id).update({
                Document.n_pages: n_pages,
                Document.n_chunks: len(chunk_records),
                Document.file_path: effective_storage_path,
            })

        if chunk_records:
            db.bulk_save_objects(chunk_records)

        db.commit()

    return len(chunk_records)



def run_mineru_on_file(pdf_path: str, doc_id: int, chunking_mode: ChunkingMode = ChunkingMode.token_fixed, document_version_id: int | None = None, storage_path: str | None = None) -> int:
    base_dir = settings.files_dir
    full_pdf_path = Path(base_dir) / pdf_path
    mineru_enabled = os.getenv("MINERU_ENABLED", "false").lower() in ("1", "true", "yes")

    if not mineru_enabled:
        print("MinerU disabled, using pypdf fallback directly", flush=True)
        pages = extract_pdf_pages_with_pypdf(full_pdf_path)
        fallback_chunks = make_simple_chunks_from_pages(pages)

        if not fallback_chunks:
            raise RuntimeError("pypdf fallback failed to extract text")

        return save_text_chunks(doc_id, fallback_chunks, len(pages), document_version_id=document_version_id, storage_path=storage_path)

    try:
        middle_json_path = process_pdf_with_mineru(pdf_path, doc_id, base_dir, storage_path=storage_path)

        with open(middle_json_path, "r", encoding="utf-8") as f:
            middle_data = json.load(f)

        pdf_info = middle_data.get("pdf_info", middle_data)
        if not isinstance(pdf_info, list):
            raise ValueError("Invalid MinerU middle json: expected list under `pdf_info`")

        chunks = chunk_text(
            pdf_info=pdf_info,
            mode=chunking_mode,
            doc_id=doc_id,
            base_url=settings.base_url,
            max_tokens=800,
            overlap_tokens=150,
            min_chunk_tokens=20,
        )

        page_indices = [int(p.get("page_idx", -1)) for p in pdf_info if isinstance(p, dict)]
        n_pages = (max(page_indices) + 1) if page_indices else 0

        normalized_chunks = []
        for chunk in chunks:
            normalized_chunks.append({
                "page_num": int(chunk["start_page"]),
                "content": chunk["chunk_text"],
                "token_count": int(chunk["token_count"]),
            })

        return save_text_chunks(doc_id, normalized_chunks, n_pages, document_version_id=document_version_id, storage_path=storage_path)

    except Exception as e:
        print("MinerU ingestion failed, falling back to pypdf", flush=True)
        print("Fallback reason:", repr(e), flush=True)

        pages = extract_pdf_pages_with_pypdf(full_pdf_path)
        fallback_chunks = make_simple_chunks_from_pages(pages)

        if not fallback_chunks:
            raise RuntimeError("Both MinerU and pypdf fallback failed to extract text") from e

        return save_text_chunks(doc_id, fallback_chunks, len(pages), document_version_id=document_version_id, storage_path=storage_path)



