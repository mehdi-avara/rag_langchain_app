def detect_type(file_bytes: bytes) -> str:
    """Detect if file is PDF or image."""
    if file_bytes.startswith(b'%PDF'):
        return 'pdf'
    if file_bytes.startswith(b'---'):
        return 'md'
    if file_bytes.startswith(b'#'):
        return 'txt'
    if file_bytes.startswith(b'![') and file_bytes.endswith(b']'):
        return 'image'
    return 'unknown'

def extract_text_from_md(file_bytes: bytes) -> Tuple[str, int, List[Dict]]:
    """Extract text from markdown file."""
    # Try robust decoding: UTF-8 first, then common fallbacks; finally replace errors
    candidate_encodings = ['utf-8', 'utf-8-sig', 'cp1252', 'latin-1']
    for enc in candidate_encodings:
        try:
            text = file_bytes.decode(enc)
            break
        except UnicodeDecodeError:
            continue
    else:
        # Last resort: decode with utf-8 replacing invalid bytes
        text = file_bytes.decode('utf-8', errors='replace')

    # Normalize newlines to "\n"
    text = text.replace('\r\n', '\n').replace('\r', '\n')
    return text, 1, []



def run_mineru_sync(original_pdf_path: str, doc_dir: str):
    """
    Run MinerU process synchronously (blocking mode).
    Safe to use inside Celery worker.
    """
    cmd = [
        "taskset", "-c", "0-5",
        settings.mineru_running_address,
        "-p", str(original_pdf_path),
        "-o", str(doc_dir)
    ]

    env = os.environ.copy()
    
    try:
        result = subprocess.run(
            cmd,
            env=env,
            check=True,
            capture_output=True,
            text=True,
            cwd=doc_dir
        )
        print("MinerU STDOUT:\n", result.stdout)
        print("MinerU STDERR:\n", result.stderr)
        return result.stdout

    except subprocess.CalledProcessError as e:
        # Print everything on failure
        print("MinerU FAILED")
        print("Return code:", e.returncode)
        print("STDOUT:\n", e.stdout)
        print("STDERR:\n", e.stderr)

        raise e


def process_pdf_with_mineru(pdf_path: str, doc_id: int, base_dir: str) -> str:
    """
    Process PDF with MinerU and return path to generated `_middle.json`.
    
    Args:
        pdf_path: PDF file content as bytes
        doc_id: Document ID for directory structure
        base_dir: Base directory (FILES_DIR)
    
    Returns:
        Path to the generated middle JSON file
    """
    # Create directory structure
    doc_dir = Path(base_dir) / str(doc_id)
    doc_dir.mkdir(parents=True, exist_ok=True)
    run_mineru_sync(Path(base_dir) / pdf_path, doc_dir)
    middle_json_file = get_full_processed_file_path(doc_dir, "_middle.json")
    if middle_json_file:
        return middle_json_file
    
    raise Exception("No _middle.json file generated by MinerU")

def run_mineru_on_file(pdf_path: str, doc_id: int, chunking_mode: ChunkingMode = ChunkingMode.token_fixed) -> int:
    """
    Background task to process PDF with MinerU.
    """
    
    # Process PDF with MinerU
    base_dir = settings.files_dir
    middle_json_path = process_pdf_with_mineru(pdf_path, doc_id, base_dir)

    # Read the generated middle JSON file
    with open(middle_json_path, "r", encoding="utf-8") as f:
        middle_data = json.load(f)

    pdf_info = middle_data.get("pdf_info", middle_data)
    if not isinstance(pdf_info, list):
        raise ValueError("Invalid MinerU middle json: expected list under `pdf_info`")

    # Build chunks directly from middle json (MM_MD for content, NLP_MD for embedding text)
    chunks = chunk_text(
        pdf_info=pdf_info,
        mode=chunking_mode,
        doc_id=doc_id,
        base_url=settings.base_url,
        max_tokens=800,
        overlap_tokens=150,
        min_chunk_tokens=20,
    )

    # Page count from middle json page indices
    page_indices = [int(p.get("page_idx", -1)) for p in pdf_info if isinstance(p, dict)]
    n_pages = (max(page_indices) + 1) if page_indices else 0
    
    # Generate embeddings for text chunks
    text_embeddings = []
    embedding_chunks = [f"search_document: {c['chunk_embedding_text']}" for c in chunks]
    if chunks:
        text_embeddings = generate_embeddings_for_chunks(embedding_chunks)
    
    # Create chunk records
    chunk_records = []
    current_pos = 0
    # Add text chunks
    for i, chunk in enumerate(chunks):
        chunk_text_mm = chunk["chunk_text"]
        start_pos = current_pos
        end_pos = start_pos + len(chunk_text_mm)
        current_pos = end_pos
        
        # Get embedding for this chunk
        chunk_embedding = text_embeddings[i] if i < len(text_embeddings) else None
        
        holder = Chunk(
            doc_id=doc_id,
            page_num=int(chunk["start_page"]),
            token_count=int(chunk["token_count"]),
            content=chunk_text_mm,
            start_pos=start_pos,
            end_pos=end_pos,
            chunk_type="text",
            embedding=chunk_embedding
        )
        chunk_records.append(holder)
    
    # Update chunk IDs
    for i, chunk in enumerate(chunk_records):
        chunk.vdb_id = f"{doc_id}_{i}"
        chunk.es_id = f"{doc_id}_{i}"
    
    with db_session() as db:
        # Update document record
        db.query(Document).filter(Document.id == doc_id).update({
            Document.n_pages: n_pages,
            Document.n_chunks: len(chunks),
            Document.file_path: str(doc_id) , # Store relative path
        })
        db.bulk_save_objects(chunk_records)
        db.commit()
